test('Follow-up detects stale selection context and carries Apply/Reject outcome', function()
  local b = buffer('original'); local t, r = request(b, { 0, 0, 0, 8 })
  t.client:emit('done', result(r, 'changed')); S.resolve(t, 'apply')
  assert(not pcall(S.send, t, 'Explain more', nil, config))
  t.contexts[b] = E.snapshot(b)
  S.send(t, 'Explain more', nil, config)
  local payload = vim.json.decode(t.client.messages[2])
  assert(payload.previousEditorOutcome:find('applied', 1, true))
  assert(payload.attachments[1].content == 'changed')
  S.cancel(t)
end)
test('JSONL handles arbitrary chunks, CRLF and Unicode line separators', function()
  local received, errors = {}, {}
  local decode = P.decoder(function(v) received[#received + 1] = v end, function(e) errors[#errors + 1] = e end)
  local stream = vim.json.encode({ text = 'فارسی still same record yes' }) .. '\r\n' .. '{"next":true}\n'
  for i = 1, #stream do decode(stream:sub(i, i)) end
  decode(nil); assert(#received == 2 and #errors == 0 and received[2].next)
  local bad = P.decoder(function() error('invalid callback') end, function(e) errors[#errors + 1] = e end)
  bad('{'); bad(nil); assert(#errors == 1)
end)
