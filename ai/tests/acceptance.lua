  local b = buffer('abc فارسی xyz\nsecond')
  vim.api.nvim_win_set_cursor(0, { 1, 4 }); vim.cmd('normal! v2l')
  local s = E.visual(); assert(s.original == 'فار', s.original); vim.cmd('normal! \27')
  vim.api.nvim_win_set_cursor(0, { 1, 8 }); vim.cmd('normal! v2h')
  s = E.visual(); assert(s.original == 'فار', s.original); vim.cmd('normal! \27')
  vim.cmd('normal! Vj'); s = E.visual(); assert(s.kind == 'line' and s.original == text(b)); vim.cmd('normal! \27')
  vim.cmd('normal! \22'); assert(not pcall(E.visual)); vim.cmd('normal! \27')
end)
