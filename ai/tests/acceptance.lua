test('Confirmed selection prompt always creates an independent new tab', function()
  local before = #S.tabs; local previous = S.current(); local original = vim.ui.input
  vim.ui.input = function(_, callback) callback('Change this') end
  require('movim_ai').prompt(E.capture(buffer('abc'), { 0, 0, 0, 3 }), true)
  vim.ui.input = original
  assert(#S.tabs == before + 1 and S.current() ~= previous and S.current().status == 'processing')
  S.cancel(S.current()); require('movim_ai.ui').hide()
end)
-- Cross the event-loop boundary like an actual Apply command to verify undo grouping.
local undo_buffer = buffer('before\nkeep')
vim.schedule(function()
  local t, r = request(undo_buffer, { 0, 0, 1, 0 }, 'line')
  t.client:emit('done', result(r, 'after\nnew'))
  vim.schedule(function()
    S.resolve(t, 'apply')
    vim.schedule(function()
      test('One Undo reverses the complete Apply', function()
        vim.api.nvim_set_current_buf(undo_buffer); vim.cmd('undo'); assert(text(undo_buffer) == 'before\nkeep', text(undo_buffer))
      end)
      S.shutdown(); print(('PASS %d AI acceptance tests'):format(tests)); vim.cmd('qa!')
    end)
  end)
end)
