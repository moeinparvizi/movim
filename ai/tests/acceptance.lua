local fake = dofile('ai/tests/fake.lua')
local config = { adapter = fake.new, context_window = 100000, output_tokens = 4096, sensitive_policy = 'deny', sensitive_patterns = { '/%.env', '%.pem$' } }
local tests = 0
local function test(name, fn)
  local ok, err = pcall(fn)
  if not ok then print('FAIL ' .. name .. ': ' .. tostring(err)); vim.cmd('cquit 1'); return end
  tests = tests + 1; print('PASS ' .. name)
end
local function buffer(text)
  local b = vim.api.nvim_create_buf(true, false)
  vim.api.nvim_set_current_buf(b)
  vim.api.nvim_buf_set_lines(b, 0, -1, false, vim.split(text, '\n', { plain = true }))
  return b
end
local function text(b) return table.concat(vim.api.nvim_buf_get_lines(b, 0, -1, true), '\n') end
local function result(r, replacement)
  return vim.json.encode({ requestId = r.id, snapshotId = r.snapshot.id, replacementText = replacement, explanation = 'Only selection changed' })
end
local function request(b, range, kind)
  local t = S.new(); local r = S.send(t, 'Improve selection', E.capture(b, range, kind), config)
  return t, r
end
test('Full unsaved buffer and exact selection are sent; no writes before Apply/Reject', function()
  local path = vim.fn.tempname() .. '.lua'; vim.fn.writefile({ 'disk contents' }, path)
  local b = buffer('prefix\nunsaved فارسی\nsuffix'); vim.api.nvim_buf_set_name(b, path)
  local t, r = request(b, { 1, 0, 2, 0 }, 'line')
  local payload = vim.json.decode(t.client.messages[1]); assert(payload.fullBuffer == text(b)); assert(payload.selection == 'unsaved فارسی')
  t.client:emit('done', result(r, 'replacement'))
  assert(r.status == 'review' and text(b) == 'prefix\nunsaved فارسی\nsuffix')
  S.resolve(t, 'reject'); assert(text(b) == 'prefix\nunsaved فارسی\nsuffix')
  assert(table.concat(vim.fn.readfile(path), '\n') == 'disk contents'); vim.fn.delete(path)
end)
test('Unicode multiline replacement only touches selected bytes; Apply is single use', function()
  local b = buffer('پیش سلام دنیا\nخط دوم پایان')
  local t, r = request(b, { 0, #'پیش ', 1, #'خط دوم' })
  t.client:emit('done', result(r, 'جدید\n🙂'))
  S.resolve(t, 'apply'); assert(text(b) == 'پیش جدید\n🙂 پایان')
  assert(not pcall(S.resolve, t, 'apply')); assert(vim.bo[b].modified)
end)
test('Changed buffer and renamed buffer block stale Apply', function()
  local b = buffer('one\ntwo'); local t, r = request(b, { 0, 0, 0, 3 })
  t.client:emit('done', result(r, 'new')); vim.api.nvim_buf_set_lines(b, 1, 2, true, { 'changed' })
  assert(not pcall(S.resolve, t, 'apply')); assert(text(b) == 'one\nchanged')
  local t2, r2 = request(b, { 0, 0, 0, 3 }); t2.client:emit('done', result(r2, 'new'))
  vim.api.nvim_buf_set_name(b, vim.fn.tempname()); assert(not pcall(S.resolve, t2, 'apply'))
end)
test('Apply refuses disabled Undo rather than making an irreversible buffer edit', function()
  local b = buffer('stay'); local t, r = request(b, { 0, 0, 0, 4 })
  t.client:emit('done', result(r, 'new')); vim.bo[b].undolevels = -1
  assert(not pcall(S.resolve, t, 'apply')); assert(text(b) == 'stay')
  vim.bo[b].undolevels = -123456
end)
test('Concurrent tabs never cross responses, attachments or history', function()
  local a, b = buffer('alpha'), buffer('beta')
  local t1, r1 = request(a, { 0, 0, 0, 5 }); local t2, r2 = request(b, { 0, 0, 0, 4 })
  S.attach(t1, E.snapshot(a)); assert(#t2.attachments == 0)
  t2.client:emit('done', result(r2, 'B')); t1.client:emit('done', result(r1, 'A'))
  assert(r1.proposal.replacementText == 'A' and r2.proposal.replacementText == 'B')
  S.resolve(t1, 'apply'); assert(text(a) == 'A' and text(b) == 'beta')
end)
test('Cancellation, network errors and malformed/wrong-ID responses cannot apply', function()
  for _, scenario in ipairs({ 'cancel', 'network', 'partial', 'wrong' }) do
    local b = buffer('untouched'); local t, r = request(b, { 0, 0, 0, 9 }); local client = t.client
    if scenario == 'cancel' then S.cancel(t); client:emit('done', result(r, 'bad'))
    elseif scenario == 'network' then client:emit('error', 'Offline')
    elseif scenario == 'partial' then client:emit('done', '{"requestId":')
    else local data = vim.json.decode(result(r, 'bad')); data.requestId = 'another'; client:emit('done', vim.json.encode(data)) end
    assert(not pcall(S.resolve, t, 'apply')); assert(text(b) == 'untouched')
  end
end)
test('Closing active tab cancels process and fences late events', function()
  local b = buffer('stay'); local t, r = request(b, { 0, 0, 0, 4 }); local client = t.client
  S.close(t); client:emit('done', result(r, 'bad')); assert(client.closed and r.status == 'cancelled' and text(b) == 'stay')
end)
