local root = vim.env.MOVIM_TOOLS_TEST_DIR:gsub('\\', '/')
local W = require('utils.workspace')
assert(W.open(root, { startup = true }))
vim.cmd('enew')
vim.api.nvim_buf_set_lines(0, 0, -1, false, { 'first copied line', 'second copied line' })
vim.cmd('normal! yy')
local history = require('utils.clipboard_history')
assert(#history.items() > 0 and history.items()[1].lines[1] == 'first copied line', 'Yank was not captured')
vim.api.nvim_win_set_cursor(0, { 2, 0 }); vim.cmd('normal! yy')
assert(history.items()[1].lines[1] == 'second copied line' and #history.items() == 2, 'Clipboard entries should be newest first')
history.record({ 'first copied line' }, 'V')
assert(#history.items() == 2 and history.items()[1].lines[1] == 'first copied line', 'Duplicate copies should move to the front')
history.record({ 'فارسی', 'multiline' }, 'v')
assert(W.save(true))
local disk = vim.json.decode(table.concat(vim.fn.readfile(root .. '/.movim/settings.json'), '\n'))
assert(disk.preferences.clipboard.history[1].lines[1] == 'فارسی', 'Clipboard history must be saved inside .movim')
local selected = history.items()[1]
vim.api.nvim_buf_set_lines(0, 0, -1, false, { 'prefix suffix' })
vim.api.nvim_win_set_cursor(0, { 1, 7 })
history.paste(selected, { win = vim.api.nvim_get_current_win(), buf = vim.api.nvim_get_current_buf(), cursor = { 1, 7 }, insert = true })
assert(vim.deep_equal(vim.api.nvim_buf_get_lines(0, 0, -1, false), { 'prefix فارسی', 'multilinesuffix' }), 'Multiline clipboard paste must preserve all text and Unicode')
vim.cmd('stopinsert')
history.remove(1)
assert(#history.items() == 2, 'Remove clipboard item failed')
history.clear()
assert(#history.items() == 0, 'Clear clipboard history failed')
print('PASS clipboard complete')
vim.cmd('qa!')
