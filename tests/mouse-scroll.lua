local repo = vim.fn.getcwd()
local child = vim.fn.jobstart({ vim.v.progpath, '--embed', '--headless', '-u', 'NONE' }, { rpc = true })
local function request(method, ...) return vim.rpcrequest(child, method, ...) end
local function execute(code, ...) return request('nvim_exec_lua', code, { ... }) end
local function wheel(direction, count, row, col)
  for _ = 1, count do request('nvim_input_mouse', 'wheel', direction, '', 0, row or 10, col or 12) end
  vim.wait(150)
end
local ok, failure = pcall(function()
  request('nvim_ui_attach', 100, 30, { rgb = true })
  execute([[
    vim.opt.rtp:prepend(...)
    vim.o.mouse = 'a'; vim.o.scrolloff = 0; vim.o.wrap = false
    local lines = {}; for i=1,250 do lines[i]=('line %03d  '):format(i)..string.rep('long text ',30) end
    vim.api.nvim_buf_set_lines(0,0,-1,false,lines)
    vim.api.nvim_win_set_cursor(0,{8,5})
    vim.g.original_win=vim.api.nvim_get_current_win()
    local exists, scroll=pcall(require,'utils.mouse_scroll'); if exists then scroll.setup() end
    vim.cmd('redraw')
  ]], repo)
  local before = execute([[return vim.api.nvim_win_get_cursor(0)]])
  wheel('down', 18)
  assert(vim.deep_equal(before, execute([[return vim.api.nvim_win_get_cursor(vim.g.original_win)]])), 'wheel moved the edit cursor off its original line: ' .. vim.inspect(execute([[return {cur=vim.api.nvim_win_get_cursor(vim.g.original_win),active=vim.api.nvim_get_current_win(),wins=vim.api.nvim_list_wins(),loaded=package.loaded['utils.mouse_scroll']~=nil,map=vim.fn.maparg('<ScrollWheelDown>','n')}]])))
  assert(execute([[return vim.api.nvim_get_current_win()==vim.g.original_win]]), 'scroll changed editing focus')
  local visible = execute([[local s=''; for c=1,20 do s=s..vim.fn.screenstring(5,c) end; return s]])
  assert(not visible:find('line 005',1,true), 'view did not scroll')
  request('nvim_input','iX<Esc>')
  assert(vim.wait(2000,function() return execute([[return vim.api.nvim_buf_get_lines(0,7,8,false)[1]:find('X',1,true)~=nil]]) end), 'typing did not resume at original edit position')
  assert(execute([[return #vim.api.nvim_list_wins()==1]]), 'scroll view remained after typing')
  execute([[vim.api.nvim_win_set_cursor(0,{9,4})]])
  request('nvim_input','i')
  assert(vim.wait(1000,function() return execute([[return vim.fn.mode()=='i']]) end))
  before=execute([[return vim.api.nvim_win_get_cursor(0)]])
  wheel('down',15)
  assert(vim.deep_equal(before,execute([[return vim.api.nvim_win_get_cursor(vim.g.original_win)]])), 'Insert wheel moved edit cursor')
  request('nvim_input','Y<Esc>')
  assert(vim.wait(2000,function() return execute([[return vim.api.nvim_buf_get_lines(0,8,9,false)[1]:find('Y',1,true)~=nil]]) end))
  print('PASS Normal and Insert mouse scroll keeps offscreen edit position and typing resumes there')
  request('nvim_input','<Esc>')
  vim.wait(50)
  before=execute([[return vim.api.nvim_win_get_cursor(0)]])
  wheel('right',12)
  assert(vim.deep_equal(before,execute([[return vim.api.nvim_win_get_cursor(vim.g.original_win)]])), 'horizontal wheel changed cursor')
  request('nvim_input','<Esc>'); vim.wait(50)
  wheel('down',15)
  request('nvim_input_mouse','move','','',0,10,12)
  vim.wait(50)
  local clicked=execute([[local m=vim.fn.getmousepos();return {m.line,m.column-1}]])
  request('nvim_input_mouse','left','press','',0,10,12)
  request('nvim_input_mouse','left','release','',0,10,12)
  vim.wait(100)
  assert(vim.deep_equal(clicked,execute([[return vim.api.nvim_win_get_cursor(0)]])), 'click after scroll chose the wrong visible text: '..vim.inspect(clicked)..' vs '..vim.inspect(execute([[return vim.api.nvim_win_get_cursor(0)]])))
  assert(execute([[return #vim.api.nvim_list_wins()==1]]), 'click did not dismiss scroll view')
  print('PASS horizontal wheel preserves cursor and clicking scrolled text selects the visible location')
  execute([[vim.cmd('vsplit'); vim.g.other_win=vim.api.nvim_get_current_win(); vim.api.nvim_set_current_win(vim.g.original_win)]])
  local source=execute([[return {cursor=vim.api.nvim_win_get_cursor(vim.g.other_win),pos=vim.fn.win_screenpos(vim.g.other_win)}]])
  wheel('down',15,source.pos[1]+4,source.pos[2]+4)
  assert(vim.deep_equal(source.cursor,execute([[return vim.api.nvim_win_get_cursor(vim.g.other_win)]])), 'wheel in inactive split changed its cursor')
  assert(execute([[return vim.api.nvim_get_current_win()==vim.g.original_win]]), 'inactive split took focus')
  request('nvim_input','<Esc>'); vim.wait(50)
  execute([[vim.api.nvim_win_close(vim.g.other_win,true);vim.api.nvim_win_set_cursor(0,{10,4})]])
  request('nvim_input','vll'); vim.wait(100)
  local selection=execute([[return {cursor=vim.api.nvim_win_get_cursor(0),anchor=vim.fn.getpos('v'),mode=vim.fn.mode()}]])
  wheel('down',15)
  assert(vim.deep_equal(selection,execute([[return {cursor=vim.api.nvim_win_get_cursor(vim.g.original_win),anchor=vim.fn.getpos('v'),mode=vim.fn.mode()}]])), 'scroll changed visual selection')
  request('nvim_input','<Esc>'); vim.wait(50)
  print('PASS inactive split and visual selection retain their cursor, anchor and focus')
  execute([[vim.wo.foldmethod='manual'; vim.cmd('20,35fold');vim.cmd('normal! zM');vim.api.nvim_win_set_cursor(0,{8,4})]])
  wheel('down',3)
  assert(execute([[local w;for _,win in ipairs(vim.api.nvim_list_wins()) do if vim.api.nvim_win_get_config(win).relative~='' then w=win end end;return w and vim.api.nvim_win_call(w,function() return vim.fn.foldclosed(25)==20 end)]]), 'scroll view did not preserve closed folds')
  request('nvim_input','<Esc>');vim.wait(50)
end)
if not ok then print(execute([[return vim.api.nvim_exec2('messages',{output=true}).output]])) end
pcall(vim.fn.jobstop,child)
assert(ok,tostring(failure))
vim.cmd('qa!')
