local repo = vim.fn.getcwd():gsub('\\', '/')
local plugin = vim.fn.stdpath('data'):gsub('\\', '/') .. '/lazy/multiple-cursors.nvim'
assert(vim.fn.isdirectory(plugin) == 1, 'multiple-cursors.nvim must be installed')
local channel = vim.fn.jobstart({ vim.v.progpath, '--embed', '--headless', '-u', 'NONE' }, { rpc = true })
local function request(method, ...) return vim.rpcrequest(channel, method, ...) end
local function lua(code, ...) return request('nvim_exec_lua', code, { ... }) end
local ok, err = pcall(function()
  request('nvim_ui_attach', 80, 24, { rgb = true })
  lua([[
    local repo, plugin = ...
    vim.opt.rtp:prepend(repo); vim.opt.rtp:prepend(plugin)
    vim.o.mouse = 'a'
    vim.api.nvim_buf_set_lines(0, 0, -1, false, { 'alpha beta alpha', 'alpha beta' })
    require('utils.hover_word').setup()
    require('utils.mouse_hover').setup()
    require('utils.mouse_scroll').setup()
    local spec = dofile(repo .. '/lua/plugins/multicursor.lua')
    spec.config(nil, spec.opts)
    for _, mapping in ipairs(spec.keys) do
      vim.keymap.set(mapping.mode, mapping[1], mapping[2])
    end
    vim.cmd('redraw')
  ]], repo, plugin)
  request('nvim_input_mouse', 'move', '', '', 0, 0, 1)
  vim.wait(100)
  assert(lua([[return #vim.fn.getmatches() == 0]]), 'mouse movement unexpectedly highlighted a word')
  request('nvim_input', 'v4l')
  assert(vim.wait(1000, function() return lua([[return #vim.fn.getmatches() == 1]]) end), 'selection did not highlight matches')
  assert(lua([[return vim.fn.getmatches()[1].pattern:find('alpha', 1, true) ~= nil]]), 'wrong selected word')
  request('nvim_input', '\27')
  assert(vim.wait(1000, function() return lua([[return #vim.fn.getmatches() == 0]]) end), 'selection highlight did not clear')
  assert(vim.wait(1000, function() return lua([[return vim.fn.mode() == 'n']]) end), 'selection did not exit')
  request('nvim_input_mouse', 'left', 'press', '', 0, 0, 0)
  vim.wait(30)
  request('nvim_input_mouse', 'left', 'drag', '', 0, 0, 4)
  vim.wait(30)
  request('nvim_input_mouse', 'left', 'release', '', 0, 0, 4)
  assert(vim.wait(1000, function() return lua([[return vim.fn.mode() == 'v' and #vim.fn.getmatches() == 1 and vim.fn.getmatches()[1].pattern:find('alpha', 1, true) ~= nil]]) end), 'mouse selection did not highlight matches: ' .. vim.inspect(lua([[return { mode=vim.fn.mode(), matches=vim.fn.getmatches(), cursor=vim.api.nvim_win_get_cursor(0), anchor=vim.fn.getpos('v') }]])))
  request('nvim_input', '\27')
  assert(vim.wait(1000, function() return lua([[return vim.fn.mode() == 'n']]) end), 'mouse selection did not exit')
  request('nvim_input_mouse', 'left', 'press', 'C', 0, 1, 2)
  request('nvim_input_mouse', 'left', 'release', 'C', 0, 1, 2)
  assert(vim.wait(1000, function() return lua([[return require('multiple-cursors.virtual_cursors').get_num_virtual_cursors() == 1]]) end), 'normal Ctrl+Click failed')
  request('nvim_input', 'i')
  assert(vim.wait(1000, function() return lua([[return vim.fn.mode() == 'i']]) end), 'insert mode failed')
  request('nvim_input_mouse', 'left', 'press', 'C', 0, 1, 6)
  request('nvim_input_mouse', 'left', 'release', 'C', 0, 1, 6)
  assert(vim.wait(1000, function() return lua([[return require('multiple-cursors.virtual_cursors').get_num_virtual_cursors() == 2]]) end), 'insert Ctrl+Click failed')
  request('nvim_input', '\27\27')
  lua([[
    require('config.options')
    vim.cmd('enew!')
    local lines = {}; for index = 1, 100 do lines[index] = 'line ' .. index end
    vim.api.nvim_buf_set_lines(0, 0, -1, false, lines)
    vim.api.nvim_win_set_cursor(0, { 50, 0 }); vim.cmd('normal! zz'); vim.cmd('redraw')
    vim.g.scroll_before = vim.fn.line('w0')
  ]])
  request('nvim_input_mouse', 'wheel', 'down', '', 0, 5, 5)
  request('nvim_input_mouse', 'wheel', 'down', '', 0, 5, 5)
  assert(vim.wait(1000, function() return lua([[for _, win in ipairs(vim.api.nvim_list_wins()) do if vim.api.nvim_win_get_config(win).relative ~= '' then return vim.api.nvim_win_call(win,function() return vim.fn.line('w0') > vim.g.scroll_before end) end end return false]]) end), 'mouse wheel did not scroll')
  assert(lua([[return vim.api.nvim_win_get_cursor(0)[1] == 50]]), 'mouse wheel moved an onscreen cursor')
  for _=1,8 do request('nvim_input_mouse','wheel','down','',0,5,5) end
  request('nvim_input_mouse','move','','',0,5,5);vim.wait(100)
  local target=lua([[return vim.fn.getmousepos().line]])
  vim.wait(600)
  request('nvim_input_mouse','left','press','C',0,5,5)
  request('nvim_input_mouse','left','release','C',0,5,5)
  assert(vim.wait(1000,function() return lua([[return require('multiple-cursors.virtual_cursors').get_num_virtual_cursors()==1]]) end),'Ctrl+Click in scrolled view failed')
  assert(lua([[return vim.api.nvim_win_get_cursor(0)[1]==50]]),'Ctrl+Click changed original edit cursor')
  request('nvim_input','i')
  assert(vim.wait(1000,function() return lua([[return vim.fn.mode()=='i']]) end))
  request('nvim_input','Z')
  assert(vim.wait(1000,function() return lua([[local target=...;return vim.api.nvim_buf_get_lines(0,49,50,false)[1]:find('Z',1,true)~=nil and vim.api.nvim_buf_get_lines(0,target-1,target,false)[1]:find('Z',1,true)~=nil]],target) end),'multicursor typing after scroll missed one of the edit positions')
  print('PASS selection highlighting and Ctrl+Click in Normal and Insert modes')
end)
if not ok then print(vim.inspect(lua([[local edits={};for i,l in ipairs(vim.api.nvim_buf_get_lines(0,0,-1,false)) do if l:find('Z',1,true) then edits[i]=l end end;return {edits=edits,messages=vim.api.nvim_exec2('messages',{output=true}).output,mouse=vim.fn.getmousepos(),cursor=vim.api.nvim_win_get_cursor(0),wins=vim.api.nvim_list_wins(),count=require('multiple-cursors.virtual_cursors').get_num_virtual_cursors()}]]))) end
vim.fn.jobstop(channel)
assert(ok, err)
vim.cmd('qa!')
