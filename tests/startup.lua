vim.wait(1000, function() return vim.g.colors_name ~= nil end)
print('VERSION=' .. require('config.version'))
print('THEME=' .. tostring(vim.g.colors_name))
print('DATA=' .. vim.fn.stdpath('data'))
print('STATE=' .. vim.fn.stdpath('state'))
print('NORMAL=' .. vim.inspect(vim.api.nvim_get_hl(0, { name = 'Normal', link = false })))
print('ERROR=' .. vim.v.errmsg)
assert(vim.g.colors_name, 'No colorscheme loaded')
local normal = vim.api.nvim_get_hl(0, { name = 'Normal', link = false })
assert(normal.fg and normal.bg and normal.fg ~= normal.bg, 'Missing readable theme colors')
assert(vim.fn.exists(':Neotree') == 2, 'Explorer unavailable')
assert(vim.v.errmsg == '', vim.v.errmsg)
