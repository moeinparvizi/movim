local repo = vim.fn.getcwd()
vim.opt.runtimepath:prepend(repo)
local root = vim.fn.tempname()
vim.fn.mkdir(root .. '/.movim', 'p')
vim.cmd.cd(vim.fn.fnameescape(root))
local function key(value)
  vim.api.nvim_feedkeys(vim.keycode(value), 'mx', false)
end
local function contents(buf)
  return table.concat(vim.api.nvim_buf_get_lines(buf, 0, -1, false), '\n')
end
local function check()
  vim.fn.writefile({ '{"services":[{"label":"worker","type":"process","command":"node","args":["-e","require(\'fs\').writeFileSync(\'ready\',\'yes\');console.log(12345);setInterval(()=>{},1000)"]}]}' }, root .. '/.movim/services.json')
  require('utils.tasks').toggle('services')
  local panel = vim.api.nvim_get_current_buf()
  assert(contents(panel):find('worker'), 'Service missing')
  key('<CR>')
  assert(vim.wait(8000, function() return vim.fn.filereadable(root .. '/ready') == 1 end), 'Service did not start')
  assert(contents(panel):find('%[running%]'))
  vim.api.nvim_set_current_win(vim.fn.bufwinid(panel))
  key('x')
  assert(vim.wait(5000, function() return contents(panel):find('%[exit ') end), 'Service did not stop')
  key('q')
  vim.fn.writefile({ '{"connections":[{"name":"Local","driver":"SQLite","args":["fixture.db"]}]}' }, root .. '/.movim/databases.json')
  require('utils.database').open()
  local dbpanel = vim.api.nvim_get_current_buf()
  assert(contents(dbpanel):find('Local'))
  key('<CR>')
  local query = vim.api.nvim_get_current_buf()
  local function execute(sql, expected)
    vim.api.nvim_set_current_win(vim.fn.bufwinid(query))
    vim.api.nvim_buf_set_lines(query, 0, -1, false, {sql})
    key('<C-CR>')
    assert(vim.wait(8000, function()
      for _, win in ipairs(vim.api.nvim_list_wins()) do
        local buf = vim.api.nvim_win_get_buf(win)
        if vim.bo[buf].filetype == 'movim-db-result' and contents(buf):find(expected, 1, true) then return true end
      end
    end), sql)
  end
  execute('CREATE TABLE fruit(name TEXT);','OK')
  execute("INSERT INTO fruit VALUES ('apricot');",'OK')
  execute('SELECT * FROM fruit;', 'apricot')
  execute('SELECT * FROM absent;', 'no such table')
  vim.api.nvim_set_current_win(vim.fn.bufwinid(dbpanel))
  key('s')
  assert(vim.wait(5000, function() return contents(0):find('fruit') end), 'Schema missing')
  vim.api.nvim_set_current_win(vim.fn.bufwinid(dbpanel))
  local inputs = {'External client', vim.json.encode({'node', repo .. '/lua/utils/sqlite-query.cjs', 'fixture.db'})}
  vim.ui.select = function(_, _, accept) accept('Custom') end
  vim.ui.input = function(_, accept) accept(table.remove(inputs, 1)) end
  key('a')
  key('q')
  require('utils.database').open()
  assert(contents(0):find('External client'))
  vim.api.nvim_win_set_cursor(0, {5,0})
  key('<CR>')
  query = vim.api.nvim_get_current_buf()
  execute("SELECT upper(name) FROM fruit;", 'APRICOT')
end
local ok, err = xpcall(check, debug.traceback)
vim.cmd.cd(vim.fn.fnameescape(repo))
if not ok then print(err); vim.cmd('cquit 1') end
print('PASS services lifecycle, database queries, errors and schema')
vim.cmd('qa!')
