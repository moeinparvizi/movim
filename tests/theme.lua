vim.opt.rtp:prepend(vim.fn.getcwd())
vim.cmd.colorscheme('movim')
local theme = require('config.theme')
local selected = vim.fn.stdpath('state') .. '/colorscheme.txt'
vim.fn.mkdir(vim.fn.fnamemodify(selected, ':h'), 'p')
vim.fn.writefile({ 'missing-theme-on-a-new-machine' }, selected)
theme.load()
assert(vim.g.colors_name == 'movim', 'Missing saved theme must fall back without plugins')
local hl = vim.api.nvim_get_hl(0, { name = 'Normal', link = false })
assert(hl.bg == 0x1a1b26 and hl.fg == 0xc0caf5, 'Fallback must have readable colors')
assert(vim.fn.readfile(selected)[1] == 'missing-theme-on-a-new-machine', 'Fallback must preserve the user preference')
assert(theme.set('movim'))
assert(vim.fn.readfile(selected)[1] == 'movim')
assert(not theme.set('missing-theme-on-a-new-machine'))
assert(vim.fn.readfile(selected)[1] == 'movim', 'Failed theme selection must not replace the saved theme')
print('PASS theme startup, missing plugin fallback and saved preference')
vim.cmd('qa!')
