local root = vim.env.MOVIM_TOOLS_TEST_DIR:gsub('\\', '/')
vim.fn.writefile({ 'const first={one:1,two:2};', 'const second={three:3};' }, root .. '/format.js')
vim.cmd('edit ' .. vim.fn.fnameescape(root .. '/format.js'))
for _, client in ipairs(vim.lsp.get_clients()) do client:stop(true) end
local mapping = vim.fn.maparg('<leader>cf', 'n', false, true)
assert(type(mapping.callback) == 'function', 'Format shortcut is missing before LSP attaches')
assert(vim.fn.exists(':FormatLine') == 2, 'FormatLine command is missing')
vim.cmd('FormatLine')
assert(vim.wait(10000, function() return vim.api.nvim_get_current_line():find('one: 1', 1, true) ~= nil end), 'Current line was not formatted')
assert(vim.api.nvim_buf_get_lines(0, -2, -1, false)[1] == 'const second={three:3};', 'Formatting one line changed an unrelated line')
mapping.callback()
assert(vim.wait(10000, function() return table.concat(vim.api.nvim_buf_get_lines(0, 0, -1, false), '\n'):find('three: 3', 1, true) ~= nil end), 'File was not formatted')
print('PASS format complete')
vim.cmd('qa!')
