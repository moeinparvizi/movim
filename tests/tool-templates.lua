local root = vim.env.MOVIM_TOOLS_TEST_DIR:gsub('\\', '/')
local W = require('utils.workspace')
assert(W.open(root, { startup = true }))
vim.cmd('enew'); vim.bo.filetype = 'javascript'
require('lazy').load({ plugins = { 'blink.cmp' } })
local templates = require('utils.live_templates')
local ls = require('luasnip')
templates.reload()
assert(vim.tbl_contains(vim.tbl_map(function(item) return item.abbreviation end, templates.list('javascript')), 'log'), 'JavaScript log template missing')
local path = templates.path()
vim.fn.mkdir(vim.fs.dirname(path), 'p')
vim.fn.writefile({ vim.json.encode({ enabled = true, templates = {
  { abbreviation = 'hello', description = 'Project greeting', filetypes = { 'javascript' }, body = 'console.log($NAME$);$END$', variables = { NAME = '"فارسی"' } },
  { abbreviation = 'wrap', filetypes = { 'javascript' }, body = 'if ($COND$) {\n  $SELECTION$\n}$END$', variables = { COND = 'true' } },
} }) }, path)
assert(templates.reload(), 'Could not reload project templates')
local names = vim.tbl_map(function(item) return item.abbreviation end, templates.list('javascript'))
assert(vim.tbl_contains(names, 'hello'), 'Custom template missing')
assert(not vim.tbl_contains(vim.tbl_map(function(item) return item.abbreviation end, templates.list('lua')), 'hello'), 'Template leaked into wrong language')
vim.api.nvim_buf_set_lines(0, 0, -1, false, { 'hello' })
vim.api.nvim_win_set_cursor(0, { 1, 4 }); vim.cmd('startinsert!'); vim.api.nvim_feedkeys('', 'x', false)
vim.api.nvim_win_set_cursor(0, { 1, 5 })
assert(templates.expand(), 'Abbreviation did not expand')
assert(vim.api.nvim_get_current_line() == 'console.log("فارسی");', 'Named template variables were not expanded: ' .. vim.api.nvim_get_current_line())
assert(ls.jumpable(1), 'Template placeholders cannot be traversed')
ls.unlink_current(); vim.cmd('stopinsert')
vim.api.nvim_buf_set_lines(0, 0, -1, false, { 'hello' })
vim.fn.writefile({ '{invalid' }, path)
assert(not templates.reload(), 'Invalid template JSON was accepted')
assert(vim.tbl_contains(vim.tbl_map(function(item) return item.abbreviation end, templates.list('javascript')), 'hello'), 'Invalid JSON removed working templates')
vim.fn.writefile({ vim.json.encode({ enabled = true, templates = {} }) }, path)
assert(templates.reload())
assert(not vim.tbl_contains(vim.tbl_map(function(item) return item.abbreviation end, templates.list('javascript')), 'hello'), 'Removed template still exists')
vim.fn.writefile({ vim.json.encode({ enabled = true, templates = { { abbreviation = 'log', filetypes = { 'javascript' }, disabled = true } } }) }, path)
assert(templates.reload())
assert(not vim.tbl_contains(vim.tbl_map(function(item) return item.abbreviation end, templates.list('javascript')), 'log'), 'Disabled built-in template still exists')
vim.fn.writefile({ vim.json.encode({ enabled = false, templates = {} }) }, path)
assert(templates.reload() and #templates.list('javascript') == 0, 'Project cannot disable live templates')
local other = root .. '/other'; vim.fn.mkdir(other, 'p')
assert(W.open(other))
assert(templates.path():gsub('\\', '/') == other .. '/.movim/live-templates.json', 'Template settings did not follow active project')
assert(vim.tbl_contains(vim.tbl_map(function(item) return item.abbreviation end, templates.list('javascript')), 'log'), 'Template disabling leaked into another project')
local other_path = templates.path()
vim.fn.mkdir(vim.fs.dirname(other_path), 'p')
vim.fn.writefile({ vim.json.encode({ templates = { { abbreviation = 'onlyother', filetypes = { 'javascript' }, body = 'other$END$' } } }) }, other_path)
assert(templates.reload())
local broken = root .. '/broken'; vim.fn.mkdir(broken .. '/.movim', 'p')
vim.fn.writefile({ vim.json.encode({ templates = { { abbreviation = 'broken', filetypes = { 'javascript' }, body = '${1:$1}' } } }) }, broken .. '/.movim/live-templates.json')
assert(W.open(broken))
assert(not templates.reload(), 'Invalid snippet body was accepted')
assert(#templates.list('javascript') == 0, 'Snippet parse failure leaked previous project templates')
for _, snippet in ipairs(ls.get_snippets('javascript')) do assert(snippet.trigger ~= 'onlyother' or snippet.invalidated, 'Previous project snippet remains active') end
print('PASS templates complete')
vim.cmd('qa!')
